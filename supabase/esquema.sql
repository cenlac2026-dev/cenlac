-- CENLAC: tablas para Supabase (PostgreSQL).
-- Se puede pegar completo en Supabase > SQL Editor > New query > Run. La app también lo ejecuta sola al iniciar.
-- Las fechas se guardan como texto ISO (AAAA-MM-DD y AAAA-MM-DD HH:MM), igual que en la versión SQLite.

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL,
    nombre TEXT NOT NULL,
    rol TEXT NOT NULL CHECK (rol IN ('admin', 'jefe', 'agente', 'consulta')),
    clave_hash TEXT NOT NULL,
    activo INTEGER NOT NULL DEFAULT 1,
    creado TEXT NOT NULL,
    ultimo_ingreso TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_usuario_unico ON usuarios (lower(usuario));

CREATE TABLE IF NOT EXISTS madres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido TEXT NOT NULL,
    nombre TEXT NOT NULL,
    dni TEXT NOT NULL UNIQUE,
    fecha_nacimiento TEXT,
    telefono TEXT,
    direccion TEXT,
    barrio TEXT,
    localidad TEXT,
    situacion TEXT NOT NULL CHECK (situacion IN ('internada', 'domicilio')),
    tipo_internacion TEXT CHECK (tipo_internacion IN ('conjunta', 'neonatologia')),
    observaciones TEXT,
    factores_riesgo TEXT,
    patologias_cronicas TEXT,
    fecha_alta TEXT,
    alta_observaciones TEXT,
    fecha_registro TEXT NOT NULL,
    consentimiento_archivo TEXT,
    consentimiento_fecha TEXT,
    consentimiento_subido TEXT,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS bebes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madre_id BIGINT NOT NULL REFERENCES madres(id) ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    apellido_materno TEXT NOT NULL,
    fecha_nacimiento TEXT,
    factores_riesgo TEXT,
    patologias_cronicas TEXT,
    sexo TEXT,
    eg_semanas TEXT,
    eg_dias TEXT,
    peso_nacimiento TEXT
);

CREATE TABLE IF NOT EXISTS controles_bebe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bebe_id BIGINT NOT NULL REFERENCES bebes(id) ON DELETE CASCADE,
    fecha TEXT NOT NULL,
    peso DOUBLE PRECISION,
    talla DOUBLE PRECISION,
    pc DOUBLE PRECISION,
    observaciones TEXT,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    UNIQUE (bebe_id, fecha)
);

CREATE TABLE IF NOT EXISTS padres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madre_id BIGINT NOT NULL UNIQUE REFERENCES madres(id) ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    apellido TEXT NOT NULL,
    edad INTEGER,
    convive INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS extracciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madre_id BIGINT NOT NULL REFERENCES madres(id) ON DELETE CASCADE,
    fecha_hora TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('extraccion', 'estimulo')),
    cantidad_ml DOUBLE PRECISION,
    tipo_leche TEXT CHECK (tipo_leche IN ('calostro', 'transicion', 'madura')),
    caracteristicas TEXT,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_extracciones_madre ON extracciones (madre_id, fecha_hora);

CREATE TABLE IF NOT EXISTS actividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('educacion', 'limpieza', 'difusion', 'carteleria', 'salida')),
    destinatario_nombre TEXT,
    destinatario_apellido TEXT,
    material TEXT,
    descripcion TEXT,
    lugar TEXT,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS preparaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TEXT NOT NULL,
    hora_entrega TEXT NOT NULL,
    tipo_preparacion TEXT NOT NULL,
    dosis_ml DOUBLE PRECISION NOT NULL,
    frecuencia TEXT NOT NULL,
    cantidad_dosis INTEGER NOT NULL,
    bebe_nombre TEXT NOT NULL,
    bebe_apellido TEXT NOT NULL,
    servicio TEXT NOT NULL CHECK (servicio IN ('maternidad', 'neonatologia')),
    observaciones TEXT,
    fortificador TEXT,
    concentracion TEXT,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL
);

-- CENLAC en vivo: cambios recientes (para actualizar las pantallas de los demás) y quién está conectado.
CREATE TABLE IF NOT EXISTS novedades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    momento TEXT NOT NULL,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    accion TEXT NOT NULL,
    enlace TEXT
);
CREATE TABLE IF NOT EXISTS presencia (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
    visto TEXT NOT NULL
);

-- Índices para las búsquedas por madre, bebé y usuario.
CREATE INDEX IF NOT EXISTS idx_bebes_madre ON bebes (madre_id);
CREATE INDEX IF NOT EXISTS idx_madres_usuario ON madres (usuario_id);
CREATE INDEX IF NOT EXISTS idx_controles_usuario ON controles_bebe (usuario_id);
CREATE INDEX IF NOT EXISTS idx_extracciones_usuario ON extracciones (usuario_id);
CREATE INDEX IF NOT EXISTS idx_actividades_usuario ON actividades (usuario_id);
CREATE INDEX IF NOT EXISTS idx_preparaciones_usuario ON preparaciones (usuario_id);
CREATE INDEX IF NOT EXISTS idx_novedades_usuario ON novedades (usuario_id);

-- Seguridad: CENLAC se conecta con su propia contraseña de base de datos, así que no usa la API pública de Supabase.
-- Se activa RLS sin políticas para que nadie pueda leer ni escribir estas tablas con la clave pública (anon).
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE madres ENABLE ROW LEVEL SECURITY;
ALTER TABLE bebes ENABLE ROW LEVEL SECURITY;
ALTER TABLE controles_bebe ENABLE ROW LEVEL SECURITY;
ALTER TABLE padres ENABLE ROW LEVEL SECURITY;
ALTER TABLE extracciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE actividades ENABLE ROW LEVEL SECURITY;
ALTER TABLE preparaciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE novedades ENABLE ROW LEVEL SECURITY;
ALTER TABLE presencia ENABLE ROW LEVEL SECURITY;

